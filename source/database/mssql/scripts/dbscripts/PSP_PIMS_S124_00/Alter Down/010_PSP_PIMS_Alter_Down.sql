SET NOCOUNT ON
BEGIN TRY
  IF NOT EXISTS(SELECT * FROM deleted)
    RETURN;

  IF EXISTS (SELECT 1 FROM inserted, deleted WHERE inserted.CONCURRENCY_CONTROL_NUMBER != deleted.CONCURRENCY_CONTROL_NUMBER + 1 AND inserted.NOTIFICATION_ID = deleted.NOTIFICATION_ID)
    RAISERROR('CONCURRENCY FAILURE.', 16, 1)

