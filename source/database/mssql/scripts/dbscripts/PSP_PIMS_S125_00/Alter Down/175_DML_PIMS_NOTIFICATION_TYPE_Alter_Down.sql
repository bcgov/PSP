-- Update description for the "EXPROPH_APPEFFDT" type.
PRINT N'Disable the "EXPROPH_APPEFFDT" type.';
GO
DECLARE @CurrCd AS NVARCHAR (20);

SET @CurrCd = N'EXPROPH_APPEFFDT';

SELECT NOTIFICATION_TYPE_CODE
FROM   dbo.PIMS_NOTIFICATION_TYPE
WHERE  NOTIFICATION_TYPE_CODE = @CurrCd;

IF @@ROWCOUNT = 1
    UPDATE dbo.PIMS_NOTIFICATION_TYPE
    SET    DESCRIPTION                = N'Expropriation application effective date',
           CONCURRENCY_CONTROL_NUMBER = CONCURRENCY_CONTROL_NUMBER + 1
    WHERE  NOTIFICATION_TYPE_CODE = @CurrCd
GO
IF @@ERROR <> 0 SET NOEXEC ON;
