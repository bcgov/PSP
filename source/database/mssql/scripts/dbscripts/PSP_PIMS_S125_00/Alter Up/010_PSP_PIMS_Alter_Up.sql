-- Preserve DISPOSITION_AGREEMENT_ID when updating notifications.
CREATE TRIGGER [dbo].[PIMS_NOTIFY_I_S_U_TR] ON PIMS_NOTIFICATION INSTEAD OF UPDATE AS
SET NOCOUNT ON
BEGIN TRY
  IF NOT EXISTS(SELECT * FROM deleted)
    RETURN;

  -- validate concurrency control
  if exists (select 1 from inserted, deleted where inserted.CONCURRENCY_CONTROL_NUMBER != deleted.CONCURRENCY_CONTROL_NUMBER+1 AND inserted.NOTIFICATION_ID = deleted.NOTIFICATION_ID)
    raiserror('CONCURRENCY FAILURE.',16,1)


  -- update statement
  update PIMS_NOTIFICATION
    set "NOTIFICATION_ID" = inserted."NOTIFICATION_ID",
      "NOTIFICATION_TYPE_CODE" = inserted."NOTIFICATION_TYPE_CODE",
      "ACQUISITION_FILE_ID" = inserted."ACQUISITION_FILE_ID",
      "DISPOSITION_FILE_ID" = inserted."DISPOSITION_FILE_ID",
      "DISPOSITION_AGREEMENT_ID" = inserted."DISPOSITION_AGREEMENT_ID", -- Added for PSP-12086
      "DISPOSITION_OFFER_ID" = inserted."DISPOSITION_OFFER_ID",
      "DISPOSITION_SALE_ID" = inserted."DISPOSITION_SALE_ID",
      "RESEARCH_FILE_ID" = inserted."RESEARCH_FILE_ID",
      "MANAGEMENT_FILE_ID" = inserted."MANAGEMENT_FILE_ID",
      "LEASE_ID" = inserted."LEASE_ID",
	    "LEASE_PERIOD_ID" = inserted."LEASE_PERIOD_ID", -- Added for PSP-11980
      "TAKE_ID" = inserted."TAKE_ID",
      "INSURANCE_ID" = inserted."INSURANCE_ID",
      "LEASE_CONSULTATION_ID" = inserted."LEASE_CONSULTATION_ID",
      "NOTICE_OF_CLAIM_ID" = inserted."NOTICE_OF_CLAIM_ID",
      "LEASE_RENEWAL_ID" = inserted."LEASE_RENEWAL_ID",
      "EXPROP_OWNER_HISTORY_ID" = inserted."EXPROP_OWNER_HISTORY_ID",
      "AGREEMENT_ID" = inserted."AGREEMENT_ID",
      "NOTIFICATION_TRIGGER_DATE" = inserted."NOTIFICATION_TRIGGER_DATE",
      "NOTIFICATION_MESSAGE" = inserted."NOTIFICATION_MESSAGE",
      "CONCURRENCY_CONTROL_NUMBER" = inserted."CONCURRENCY_CONTROL_NUMBER",
      "APP_LAST_UPDATE_TIMESTAMP" = inserted."APP_LAST_UPDATE_TIMESTAMP",
      "APP_LAST_UPDATE_USERID" = inserted."APP_LAST_UPDATE_USERID",
      "APP_LAST_UPDATE_USER_GUID" = inserted."APP_LAST_UPDATE_USER_GUID",
      "APP_LAST_UPDATE_USER_DIRECTORY" = inserted."APP_LAST_UPDATE_USER_DIRECTORY"
    , DB_LAST_UPDATE_TIMESTAMP = getutcdate()
