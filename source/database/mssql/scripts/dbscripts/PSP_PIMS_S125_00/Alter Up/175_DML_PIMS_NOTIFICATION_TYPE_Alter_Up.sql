       (SELECT NOTIFICATION_TYPE_CODE,
               ROW_NUMBER() OVER (ORDER BY DESCRIPTION) AS ROW_NUM
        FROM   PIMS_NOTIFICATION_TYPE) AS seq
       ON seq.NOTIFICATION_TYPE_CODE = biz.NOTIFICATION_TYPE_CODE;
